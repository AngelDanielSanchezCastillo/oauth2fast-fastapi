"""
Unit tests for the oauth Alembic chain (work unit 1.4, alembic-2fast change).

No PostgreSQL and no database are required:

1. The chain shim (``migrations/oauth/env.py``) exists and dispatches to the
   shared async env shipped by ``pgsqlasync2fast_fastapi.migrations``.
2. Importing ``oauth2fast_fastapi`` registers the oauth ``ChainSpec`` under
   the ``"auth"`` lane with the exact shipping contract (package, script
   path, version table, owned tables).
3. The autogenerated baseline ``0001_initial`` is parseable via
   ``ScriptDirectory`` (zero DB) and owns exactly the ``users`` table.
4. The whole chain renders to SQL in alembic OFFLINE mode through the shared
   env (shim dispatch -> offline configure with literal_binds).

Run with: uv run pytest tests/test_migration_chains.py -v
"""

from __future__ import annotations

import os
from importlib import resources

os.environ.setdefault("SECRET_KEY", "test-secret-key-not-for-production")

from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from pgsqlasync2fast_fastapi import get_lane_chains

import oauth2fast_fastapi  # noqa: F401  (side effect: registers the chain)

SCRIPT_LOCATION = "oauth2fast_fastapi:migrations/oauth"


def _oauth_spec():
    chains = get_lane_chains("auth")
    oauth = [c for c in chains if c.package == "oauth2fast_fastapi"]
    assert len(oauth) == 1, f"expected exactly one oauth chain, got {len(oauth)}"
    return oauth[0]


def test_chain_shim_exists_and_dispatches_to_shared_env():
    shim = resources.files("oauth2fast_fastapi") / "migrations" / "oauth" / "env.py"
    assert shim.is_file()
    text = shim.read_text()
    assert "pgsqlasync2fast_fastapi.migrations" in text
    assert "run_migrations_offline" in text
    assert "run_migrations_online" in text
    assert "context.is_offline_mode()" in text


def test_oauth_chain_registered_in_auth_lane_with_contract():
    spec = _oauth_spec()
    assert spec.package == "oauth2fast_fastapi"
    assert spec.script_path == "migrations/oauth"
    assert spec.version_table == "alembic_version_oauth"
    assert spec.owned_tables == frozenset({"users", "oauth__refresh_tokens"})


def test_oauth_chain_is_first_in_auth_lane():
    # FK-proven order (design D6): oauth runs before permissions-global and
    # tenant2fast-auth. Even if sibling packages registered chains in this
    # environment, the oauth chain must start the lane.
    chains = get_lane_chains("auth")
    assert chains
    assert chains[0].package == "oauth2fast_fastapi"


def test_oauth_chain_target_metadata_holds_users():
    spec = _oauth_spec()
    assert "users" in spec.target_metadata.tables


def test_baseline_0001_initial_parseable_by_script_directory():
    cfg = Config()
    cfg.set_main_option("script_location", SCRIPT_LOCATION)
    script = ScriptDirectory.from_config(cfg)

    baseline = script.get_revision("0001")
    assert baseline.down_revision is None  # single-baseline chain

    filepath = baseline.path
    assert filepath.endswith("0001_initial.py"), filepath

    with open(filepath) as fh:
        text = fh.read()
    assert "op.create_table('users'" in text
    # Alembic renders third-party types module-qualified without importing the
    # module (alembic 1.20.0 _repr_type); the baseline must carry the import.
    assert "import sqlmodel" in text
    # Ownership: no foreign table may be proposed by this chain.
    assert "op.create_table('roles'" not in text
    assert "op.create_table('permissions'" not in text


def test_refresh_tokens_revision_chains_from_baseline():
    cfg = Config()
    cfg.set_main_option("script_location", SCRIPT_LOCATION)
    script = ScriptDirectory.from_config(cfg)

    head = script.get_current_head()
    rev = script.get_revision(head)
    assert rev is not None
    assert rev.down_revision == "0001"

    with open(rev.path) as fh:
        text = fh.read()
    assert "op.create_table('oauth__refresh_tokens'" in text
    assert "import sqlmodel" in text


def test_chain_upgrades_to_head_in_offline_mode():
    # Executes the chain shim -> shared runner env offline path: the whole
    # chain (env + versions) renders SQL without any database. Proves the
    # shim imports resolve and the baseline is loadable by alembic.
    cfg = Config()
    cfg.set_main_option("script_location", SCRIPT_LOCATION)
    cfg.set_main_option("sqlalchemy.url", "postgresql+asyncpg://u:p@h:5432/authdb")
    cfg.set_main_option("version_table", "alembic_version_oauth")
    cfg.attributes["target_metadata"] = _oauth_spec().target_metadata

    command.upgrade(cfg, "head", sql=True)
